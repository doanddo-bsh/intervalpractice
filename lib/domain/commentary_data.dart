// 유형 3(자리바꿈) 전용 문구
//
// 자리바꿈 해설은 **자리를 바꾼 뒤의 음정**을 설명하므로 위/아래가 화면과
// 반대다. 한쪽 음을 한 옥타브 옮기기 때문에, 악보에서 위에 그려진 음이
// 자리바꿈 후에는 아래 음이 된다.
//
// 유형 1과 같은 "위에 있는 음 / 아래에 있는 음" 문구를 쓰면, 유형 3에서는
// 화면에서 위에 보이는 음을 "아래에 있는 음"이라고 부르게 되어 계산이
// 맞는데도 읽는 사람이 반대로 이해한다. 그래서 (1) 해설 맨 앞에 자리바꿈
// 전 음정과 옮기는 방법(양방향)을 먼저 알리고, (2) 임시표 설명은 어느
// 음인지 화면만 보고 짚을 수 있게 "아래로 오는 / 위로 가는 음"으로 부른다.
//
// Easy 유형 3은 임시표가 없어 (2)가 아예 안 붙으므로, (1)이 없으면 해설에
// 자리바꿈 언급이 하나도 남지 않는다. 그래서 (1)은 난이도와 무관하게 붙인다.
// ---------------------------------------------------------------------

/// 유형 3 해설 맨 앞에 붙는 도입 문장 세 개.
///
/// [originalKorean] 은 자리바꿈 **전** 음정의 한글 이름("겹감7" 처럼 "도"가
/// 빠진 형태), [invertedSize] 는 자리바꿈 **후** 도수 한 글자("2")다.
///
/// 자리바꿈은 아래 음을 한 옥타브 올리는 것으로도, 위 음을 한 옥타브 내리는
/// 것으로도 할 수 있고 결과가 같다. 한쪽만 적어 두면 "반대로 옮기면 어떻게
/// 되나"라는 질문이 남으므로 둘 다 적는다.
///
/// "위아래가 바뀐다"고는 쓰지 않는다. `ProblemGenerator._maxSlotDistance`가
/// 7이라 두 음이 정확히 한 옥타브 떨어진 문제가 나오는데(대략 10문제에 1개),
/// 그때 자리바꿈 결과는 1도라 위아래라는 게 사라진다. 옮기는 동작만 서술하면
/// 그 경우에도 문장이 참이다.
